#!/usr/bin/env node
/**
 * Generate TypeScript types from the API OpenAPI document.
 * Start the API locally, then: npm run generate-api-client
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const base =
  process.env.OPENAPI_URL ||
  process.env.NEXT_PUBLIC_API_URL ||
  "http://127.0.0.1:8080";
const url = `${base.replace(/\/$/, "")}/swagger/v1/swagger.json`;
const out = "src/lib/api-schema.ts";

const banner = `/* AUTO-GENERATED by npm run generate-api-client — do not edit */\n`;

execSync(`npx openapi-typescript "${url}" -o "${out}"`, { stdio: "inherit" });
writeFileSync(out, banner + readFileSync(out, "utf8"));
console.log(`Wrote ${out} from ${url}`);
