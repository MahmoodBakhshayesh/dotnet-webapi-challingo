read_env() {

  local file="$1"

  [[ -f "$file" ]] || { echo "Missing $file" >&2; exit 1; }

  while IFS= read -r line || [[ -n "$line" ]]; do

    line="${line//$'\r'/}"

    [[ -z "$line" || "$line" =~ ^[[:space:]]*# ]] && continue

    [[ "$line" =~ ^([^=]+)=(.*)$ ]] || continue

    printf '%s=%s\n' "${BASH_REMATCH[1]}" "${BASH_REMATCH[2]}"

  done < "$file"

}



declare -A OUT PRESERVE

should_skip() {

  case "$1" in

    TAG|REGISTRY|NEXT_PUBLIC_*) return 0 ;;

  esac

  return 1

}



while IFS='=' read -r k v; do

  case "$k" in REGISTRY_HOST_PORT) PRESERVE["$k"]="$v" ;; esac

done < <(read_env "$SERVER_ENV" 2>/dev/null || true)

while IFS='=' read -r k v; do

  should_skip "$k" || OUT["$k"]="$v"

done < <(read_env "$API_ENV")

while IFS='=' read -r k v; do

  [[ "$k" == TAG ]] && continue

  should_skip "$k" || OUT["$k"]="$v"

done < <(read_env "$WEB_ENV")



REGISTRY_HOST_PORT="${PRESERVE[REGISTRY_HOST_PORT]:-}"
if [[ -z "$REGISTRY_HOST_PORT" ]]; then
  PUSH_REG="$(grep -E '^REGISTRY=' "$API_ENV" | head -1 | cut -d= -f2-)"
  if [[ "$PUSH_REG" =~ :([0-9]+)$ ]]; then
    REGISTRY_HOST_PORT="${BASH_REMATCH[1]}"
  else
    REGISTRY_HOST_PORT="8585"
  fi
fi
OUT[REGISTRY]="127.0.0.1:${REGISTRY_HOST_PORT}"
OUT[REGISTRY_HOST_PORT]="$REGISTRY_HOST_PORT"

OUT[API_VERSION]="$(grep -E '^TAG=' "$API_ENV" | head -1 | cut -d= -f2)"

OUT[WEB_VERSION]="$(grep -E '^TAG=' "$WEB_ENV" | head -1 | cut -d= -f2)"

OUT[WORKER_VERSION]="$(grep -E '^TAG=' "$API_ENV" | head -1 | cut -d= -f2-)"

OUT["${ENV_PREFIX}_API_IMAGE"]="127.0.0.1:${REGISTRY_HOST_PORT}/${DOCKER_PREFIX}-api:latest"

OUT["${ENV_PREFIX}_WEB_IMAGE"]="127.0.0.1:${REGISTRY_HOST_PORT}/${DOCKER_PREFIX}-web:latest"

OUT["${ENV_PREFIX}_WORKER_IMAGE"]="127.0.0.1:${REGISTRY_HOST_PORT}/${DOCKER_PREFIX}-worker:latest"



# Prefer Python for correct multi-layer unquote (passwords with # were remangled by GUI/sync).
unquote_env_value() {
  local v="$1"
  if command -v python3 >/dev/null 2>&1; then
    OUT_VAL="$v" python3 - <<'PY'
import os
v = os.environ.get("OUT_VAL", "")
def once(x: str) -> str:
    x = x.strip()
    if len(x) >= 2 and x[0] == '"' and x[-1] == '"':
        inner, out, i = x[1:-1], [], 0
        while i < len(inner):
            if inner[i] == "\\" and i + 1 < len(inner) and inner[i + 1] in '"\\':
                out.append(inner[i + 1]); i += 2; continue
            out.append(inner[i]); i += 1
        return "".join(out)
    if len(x) >= 2 and x[0] == "'" and x[-1] == "'":
        return x[1:-1]
    return x
for _ in range(40):
    n = once(v)
    if n == v:
        break
    v = n
print(v, end="")
PY
    return
  fi
  local i n prev
  for ((i = 0; i < 40; i++)); do
    prev="$v"
    n=${#v}
    if (( n >= 2 )) && [[ ${v:0:1} == '"' && ${v:n-1:1} == '"' ]]; then
      v="${v:1:n-2}"
      v="${v//\\\"/\"}"
      v="${v//\\\\/\\}"
    elif (( n >= 2 )) && [[ ${v:0:1} == "'" && ${v:n-1:1} == "'" ]]; then
      v="${v:1:n-2}"
    else
      break
    fi
    [[ "$v" == "$prev" ]] && break
  done
  printf '%s' "$v"
}

format_env_value() {
  local v
  v="$(unquote_env_value "$1")"
  if [[ "$v" =~ [[:space:]\"\'\\#] || "$v" =~ [=] ]]; then
    v="${v//\\/\\\\}"
    v="${v//\"/\\\"}"
    printf '"%s"' "$v"
  else
    printf '%s' "$v"
  fi
}

# Always rebuild Npgsql string from POSTGRES_* (Username must match POSTGRES_USER).
_pg_user="$(unquote_env_value "${OUT[POSTGRES_USER]:-scaffoldadmin}")"
