  OUT[Redis__ConnectionString]="redis:6379,password=$(unquote_env_value "${OUT[REDIS_PASSWORD]}"),abortConnect=false"
fi

write_kv() {

  local k="$1"

  [[ -n "${OUT[$k]:-}" ]] || return 0
  local v
  v="$(format_env_value "${OUT[$k]}")"
  printf '%s=%s\n' "$k" "$v"

}



