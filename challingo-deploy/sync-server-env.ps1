$lines = New-Object System.Collections.Generic.List[string]

foreach ($item in $order) {

    if ($item -eq '') { $lines.Add(''); continue }

    if ($item.StartsWith('#')) { $lines.Add($item); continue }

    if ($merged.ContainsKey($item)) {

        $lines.Add((Format-EnvLine -Key $item -Value $merged[$item]))

        $merged.Remove($item) | Out-Null

    }

}



foreach ($key in ($merged.Keys | Sort-Object)) {

    $lines.Add((Format-EnvLine -Key $key -Value $merged[$key]))

}



$text = ($lines -join "`n") + "`n"

$utf8 = New-Object System.Text.UTF8Encoding $false

[System.IO.File]::WriteAllText($serverEnvPath, $text, $utf8)



Write-Host "Updated $serverEnvPath" -ForegroundColor Green

Write-Host "  API_VERSION=$($api['TAG'])  WEB_VERSION=$($web['TAG'])  WORKER_VERSION=$($api['TAG'])" -ForegroundColor DarkGray

Write-Host "  POSTGRES_HOST_PORT=$($api['POSTGRES_HOST_PORT'])  API_HOST_PORT=$($api['API_HOST_PORT'])  WEB_HOST_PORT=$($web['WEB_HOST_PORT'])" -ForegroundColor DarkGray



$pgPort = $api['POSTGRES_HOST_PORT']

if ($pgPort) {

    $prev = $ErrorActionPreference
    $ErrorActionPreference = 'SilentlyContinue'
    $dockerPs = $null
    if (Get-Command docker -ErrorAction SilentlyContinue) {
        try {
            $dockerPs = & docker ps --format '{{.Ports}}' 2>$null
        } catch {
            $dockerPs = $null
        }
    }
    $ErrorActionPreference = $prev

    if ($dockerPs -match ":$pgPort->") {
        Write-Host "  Note: host port $pgPort is already mapped by a running container. Use another POSTGRES_HOST_PORT in api.env if this is not your project postgres." -ForegroundColor Yellow
    }

}

